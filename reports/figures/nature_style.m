function nature_style()
% Shared Nature-style defaults for the report figures.
set(groot, 'defaultFigureColor', 'w');
set(groot, 'defaultAxesColor', 'w');
set(groot, 'defaultAxesFontName', 'Arial');
set(groot, 'defaultTextFontName', 'Arial');
set(groot, 'defaultAxesFontSize', 7);
set(groot, 'defaultTextFontSize', 7);
set(groot, 'defaultAxesLineWidth', 0.6);
set(groot, 'defaultAxesBox', 'off');
set(groot, 'defaultAxesTickDir', 'out');
set(groot, 'defaultAxesXColor', [0.25 0.27 0.30]);
set(groot, 'defaultAxesYColor', [0.25 0.27 0.30]);
set(groot, 'defaultAxesGridColor', [0.85 0.87 0.89]);
set(groot, 'defaultAxesTitleFontWeight', 'normal');
set(groot, 'defaultLegendBox', 'off');
set(groot, 'defaultLegendFontSize', 7);
end
